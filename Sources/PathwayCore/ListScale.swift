import Foundation

/// Масштаб списка файлов: размер иконок и всё, что от него считается.
///
/// Настройка приложения, а не папки: живёт в TabsModel рядом с sort и
/// showHiddenFiles, раздаётся всем вкладкам и сохраняется между запусками.
///
/// Ступени, а не плавный диапазон: NSImage отдаёт растр под конкретный кегль,
/// и промежуточные 27 px рисуются мылом там, где 24 и 32 резки. Плавность
/// ползунка купилась бы качеством картинки на каждом промежуточном значении.
public enum ListScale: Int, CaseIterable, Sendable {
    case compact = 0
    case normal = 1
    case medium = 2
    case large = 3
    case huge = 4

    /// Нынешний вид списка. Он же умолчание: доработка не вправе менять
    /// картинку тем, кто про ползунок не просил.
    public static let `default` = ListScale.normal

    public var title: String {
        switch self {
        case .compact: "Компактный"
        case .normal: "Обычный"
        case .medium: "Средний"
        case .large: "Крупный"
        case .huge: "Огромный"
        }
    }

    /// Сторона иконки — ведущая величина: её задаёт ползунок, остальное
    /// выводится из неё.
    public var iconSize: CGFloat {
        switch self {
        case .compact: 14
        case .normal: 16
        case .medium: 24
        case .large: 32
        case .huge: 48
        }
    }

    /// Высота строки: иконка плюс постоянный воздух сверху и снизу.
    ///
    /// Слагаемое, а не множитель: пропорциональный отступ на компактной ступени
    /// слепил бы строки, а на огромной развёл бы их вдвое дальше, чем нужно.
    public var rowHeight: CGFloat { iconSize + 8 }

    /// Кегль имени файла.
    ///
    /// Растёт медленнее иконки и задан таблицей, а не формулой: поднятый
    /// пропорционально, к 48 px текст стал бы заголовком, а не именем файла.
    public var fontSize: CGFloat {
        switch self {
        case .compact: 11
        case .normal: 12
        case .medium: 13
        case .large: 14.5
        case .huge: 16
        }
    }

    /// Кегль заголовков колонок — на пункт мельче содержимого: шапка это
    /// подпись, а не данные.
    public var headerFontSize: CGFloat { fontSize - 1 }

    /// Кегль имени ветки в чипе. От него чип считает всю свою геометрию.
    ///
    /// Полтора пункта мельче имени файла, а не один: на обычной ступени это
    /// даёт ровно 10.5 — размер, на котором чип жил до появления масштаба.
    /// Иначе доработка сдвинула бы вид списка тем, кто ползунок не трогал.
    public var branchFontSize: CGFloat { fontSize - 1.5 }

    /// Во сколько раз шире стартовая ширина колонки против обычной ступени.
    ///
    /// Считается по кеглю, а не по иконке: ширину колонки занимает текст, и на
    /// 16 pt дата «28 авг. 2026 г., 15:37» в отведённые под 12 pt точки не
    /// помещается — колонка обрезала бы её на каждой строке.
    ///
    /// Только имя получает вдобавок прирост иконки: остальные колонки значка
    /// не рисуют, и растить их на него значило бы отдавать место впустую.
    public var columnWidthFactor: CGFloat {
        fontSize / ListScale.default.fontSize
    }

    /// Насколько шире колонка имени сверх общего коэффициента: иконка и зазор
    /// до текста съедают её ширину, а имя файла должно остаться читаемым.
    public var nameColumnExtraWidth: CGFloat {
        iconSize - ListScale.default.iconSize
    }

    /// Соседняя ступень или nil на краю шкалы.
    ///
    /// nil, а не сама себя: вызывающий отличает «шагнули» от «дальше некуда»
    /// и вправе погасить команду, а не молча ничего не делать.
    public func stepped(by delta: Int) -> ListScale? {
        ListScale(rawValue: rawValue + delta)
    }
}
