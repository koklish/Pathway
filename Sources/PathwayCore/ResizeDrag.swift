import Foundation

/// Пересчёт размера панели при перетаскивании её границы.
///
/// В Core, а не во вью, по одной причине: это единственное место, где ошибка
/// не видна глазами на статичном экране — она проявляется только в движении,
/// колебанием между двумя значениями. Чистая функция проверяется тестом, вью
/// остаётся сборкой из готовых частей.
public enum ResizeDrag {

    /// Куда растёт панель относительно движения курсора.
    public enum Growth: Sendable {
        /// Движение по оси увеличивает размер: секция над разделителем, за
        /// который тянут вниз.
        case direct
        /// Движение по оси уменьшает размер: панель, прижатая к правому краю,
        /// расширяется движением влево.
        case inverted
    }

    /// Новый размер по положению курсора.
    ///
    /// Считается от начала жеста — `start` и `from` берутся один раз, когда
    /// кнопку нажали, и дальше не меняются. Складывать приращения кадров
    /// нельзя: панель уезжала бы кратно быстрее курсора.
    ///
    /// Координаты обязаны приходить из неподвижной системы отсчёта — окна, а не
    /// самой панели. Ручка лежит на её границе и едет вместе с ней: в
    /// собственных координатах курсор, сдвинувшийся на 10 pt, после переезда
    /// ручки под него снова оказывается на нуле. Размер откатывается, на
    /// следующем кадре растёт опять, и это колебание видно как дёрганье.
    public static func size(
        start: CGFloat,
        from startPoint: CGFloat,
        to currentPoint: CGFloat,
        growth: Growth,
        limits: ClosedRange<CGFloat>
    ) -> CGFloat {
        let moved = currentPoint - startPoint
        let size = growth == .direct ? start + moved : start - moved
        return min(max(size, limits.lowerBound), limits.upperBound)
    }
}
